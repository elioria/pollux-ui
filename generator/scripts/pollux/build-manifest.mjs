#!/usr/bin/env node
// SPEC-008: rollout manifest + entity inventory.
// Writes docs/operations/pollux-rollout-manifest.json (metadata hash per
// entity, template tree hash, generated entity count) and
// docs/operations/pollux-rollout-inventory.md (classification table).
// Re-run after any regeneration; commit the outputs with the regen.
import { execSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  '../..'
);
const jsonDir = path.join(repoRoot, 'json-files');
const outDir = path.join(repoRoot, 'docs/operations');

const sha256 = (data) => crypto.createHash('sha256').update(data).digest('hex');

const git = (cmd) =>
  execSync(`git ${cmd}`, { cwd: repoRoot, encoding: 'utf8' }).trim();

const SENSITIVE_FLAGS = [
  'fnrAdmpermView',
  'fnrAdmpermEdit',
  'fedAdmpermView',
  'fedAdmpermEdit',
];

const entities = [];
const skipped = [];

for (const file of fs.readdirSync(jsonDir).filter((f) => f.endsWith('.json'))) {
  const raw = fs.readFileSync(path.join(jsonDir, file), 'utf8');
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch {
    skipped.push(file);
    continue;
  }
  const attributes = parsed?.data?.attributes;
  if (!attributes) {
    skipped.push(file);
    continue;
  }
  const name = file.replace(/\.json$/, '');
  const fieldNames = attributes.map((a) => a.name);
  entities.push({
    entity: name,
    metadataHash: sha256(raw),
    fieldCount: attributes.length,
    permissions: ['read', 'create', 'update', 'delete'],
    sensitiveFieldFlags: attributes
      .filter((a) => SENSITIVE_FLAGS.some((flag) => a[flag] === true))
      .map((a) => a.name),
    deletionMode: fieldNames.includes('deleted_at') ? 'soft' : 'hard',
    concurrencyToken: fieldNames.includes('updated_at') ? 'updatedAt' : 'none',
    routes: [`/generated/${name}`, `/generated-server/${name}`],
    generatedDir: `src/app/(private)/generated/${name}`,
  });
}

entities.sort((a, b) => a.entity.localeCompare(b.entity));

const manifest = {
  generatedAt: new Date().toISOString(),
  templateCommit: git('rev-parse HEAD'),
  templateTreeHash: git('rev-parse HEAD:_templates/pollux'),
  entityCount: entities.length,
  skippedStubs: skipped,
  entities,
};

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, 'pollux-rollout-manifest.json'),
  JSON.stringify(manifest, null, 2) + '\n'
);

const rows = entities
  .map(
    (e) =>
      `| ${e.entity} | ${e.fieldCount} | ${e.deletionMode} | ${e.concurrencyToken} | ${
        e.sensitiveFieldFlags.length ? e.sensitiveFieldFlags.join(', ') : '—'
      } | \`${e.routes.join('`, `')}\` |`
  )
  .join('\n');

fs.writeFileSync(
  path.join(outDir, 'pollux-rollout-inventory.md'),
  `# Pollux rollout inventory (generated)

Generated by \`node scripts/pollux/build-manifest.mjs\` — do not hand-edit.
Template commit: \`${manifest.templateCommit}\` · pollux template tree: \`${manifest.templateTreeHash}\`
Entities: **${manifest.entityCount}** valid · skipped stubs: ${skipped.join(', ') || 'none'}.

All entities declare the full \`read/create/update/delete\` permission set in
\`src/features/auth/permissions.ts\` (admin role only; the \`user\` role has no
generated-entity permissions). No entity metadata contains \`deleted_at\`, so
deletion is hard everywhere. Entities with \`updated_at\` support the
\`expectedUpdatedAt\` optimistic-concurrency token.

| entity | fields | deletion | concurrency | sensitive field flags | routes |
|---|---|---|---|---|---|
${rows}
`
);

console.log(
  `manifest: ${manifest.entityCount} entities, template ${manifest.templateCommit.slice(0, 8)}, ${skipped.length} stubs skipped`
);
